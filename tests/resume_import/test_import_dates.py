"""Dates a text states (rimport.dates)."""
import pytest
from rimport.dates import finest, is_iso_date, stated_dates


@pytest.mark.parametrize("text, expected", [
    ("2019", {"2019"}),
    ("Jan 2023 – Present", {"2023", "2023-01"}),
    ("June 2019 - December 2022", {"2019", "2019-06", "2022", "2022-12"}),
    ("Jun. 2019", {"2019", "2019-06"}),
    ("June, 2019", {"2019", "2019-06"}),
    ("Sept 2019", {"2019", "2019-09"}),
    ("SEPTEMBER 2019", {"2019", "2019-09"}),
    ("Jun '19", {"2019", "2019-06", "1919", "1919-06"}),
    ("Jun ’19", {"2019", "2019-06", "1919", "1919-06"}),
    ("06/2019", {"2019", "2019-06"}),
    ("6/2019", {"2019", "2019-06"}),
    ("06-2019", {"2019", "2019-06"}),
    ("06.2019", {"2019", "2019-06"}),
    ("2019-06", {"2019", "2019-06"}),
    ("2019/06", {"2019", "2019-06"}),
    ("06/19", {"2019", "2019-06", "1919", "1919-06"}),
    ("2019-06-03", {"2019", "2019-06", "2019-06-03"}),
    ("2019/06/03", {"2019", "2019-06", "2019-06-03"}),
    ("June 3, 2019", {"2019", "2019-06", "2019-06-03"}),
    ("June 3rd 2019", {"2019", "2019-06", "2019-06-03"}),
    ("3 June 2019", {"2019", "2019-06", "2019-06-03"}),
    ("03/06/2019", {"2019", "2019-03", "2019-03-06", "2019-06", "2019-06-03"}),
    ("03.06.2019", {"2019", "2019-03", "2019-03-06", "2019-06", "2019-06-03"}),
    ("13/06/2019", {"2019", "2019-06", "2019-06-13"}),
    ("Summer 2019", {"2019"}),
    ("Q3 2019", {"2019"}),
])
def test_stated_dates(text, expected):
    assert stated_dates(text) == expected


@pytest.mark.parametrize("text, expected", [
    ("2019-2022", {"2019", "2022"}),  # a range of years, not 2019-20
    ("2017-18", {"2017"}),  # month 18 is not a month
    ("2019-02-30", {"2019"}),  # not a real day
    ("13/2019", {"2019"}),
    ("serving 2M requests; 300 stars; 12345 users; 20190", set()),
    ("Python 3, Go 1.21", set()),
    ("mayor 2019, summary 2020", {"2019", "2020"}),  # no month inside a word
    ("1899 and 2100", set()),
])
def test_what_is_not_a_date(text, expected):
    assert stated_dates(text) == expected


def test_is_iso_date():
    assert is_iso_date("2019") and is_iso_date("2019-06") and is_iso_date("2019-02-28")
    for value in ("2019-13", "2019-02-30", "2019-6", "June 2019", "2019-06\n", 2019, None):
        assert not is_iso_date(value)


def test_finest_drops_coarser_forms():
    assert finest({"2019", "2019-06", "2022", "2022-12", "2022-12-01", "2023"}) == ["2019-06", "2022-12-01", "2023"]
